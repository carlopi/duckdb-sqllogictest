#!/usr/bin/env python3
"""Embed the bundled sqllogictests into the sqllogictest extension.

Reads a list of test paths and emits a C++ table of their contents, served by the extension under
sqllogic://. The list is checked in so the selection is reviewable; the content is read from the
tree at build time so it cannot drift from the tests themselves.

Usage: generate_bundled_sqllogictests.py <list> <duckdb root> <output.cpp>
"""
import os
import sys

if len(sys.argv) != 4:
    print(__doc__)
    sys.exit(1)

list_path, root, output_path = sys.argv[1:4]

with open(list_path) as f:
    tests = [line.strip() for line in f if line.strip() and not line.startswith("#")]


def as_c_string(data: bytes) -> str:
    # Escaped rather than raw: a test may contain any byte sequence, and \0 or a quote would end it.
    out = []
    for byte in data:
        char = chr(byte)
        if char == '"':
            out.append('\\"')
        elif char == "\\":
            out.append("\\\\")
        elif char == "\n":
            out.append("\\n")
        elif 32 <= byte < 127:
            out.append(char)
        else:
            out.append(f"\\x{byte:02x}\" \"")  # split so a following hex digit is not absorbed
    return "".join(out)


with open(output_path, "w") as out:
    out.write("// Generated by scripts/generate_bundled_sqllogictests.py - do not edit.\n")
    out.write('#include "bundled_tests.hpp"\n\nnamespace duckdb {\n\n')
    out.write("const BundledTest BUNDLED_TESTS[] = {\n")
    embedded = 0
    for test in tests:
        full = os.path.join(root, test)
        if not os.path.exists(full):
            print(f"warning: {test} is in the list but not in the tree, skipping", file=sys.stderr)
            continue
        with open(full, "rb") as f:
            content = f.read()
        # Served under sqllogic://<provider>/<path below test/sql/>. The provider segment is
        # reserved from the start: another extension may one day bundle its own tests, and the
        # paths are public the moment anyone types one into a CI script.
        served = "duckdb/" + (test[len("test/sql/"):] if test.startswith("test/sql/") else test)
        out.write(f'    {{"{served}", "{as_c_string(content)}", {len(content)}}},\n')
        embedded += 1
    out.write("};\n\n")
    out.write("const idx_t BUNDLED_TEST_COUNT = sizeof(BUNDLED_TESTS) / sizeof(BundledTest);\n\n")
    out.write("} // namespace duckdb\n")

print(f"embedded {embedded} of {len(tests)} listed tests into {output_path}")
